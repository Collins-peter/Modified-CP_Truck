/**
 * Resolves a nav item to its icon component.
 * Allows passing a pre-rendered JSX element, an icon key string,
 * or automatically infers the icon from item.label or item.path.
 */
export const getNavIcon = (item, iconClassName = '') => {
  if (React.isValidElement(item?.icon)) {
    return item.icon;
  }

  const key = (
    typeof item?.icon === 'string'
      ? item.icon
      : `${item?.label || ''} ${item?.path || ''}`
  ).toLowerCase();

  let IconComponent = DefaultNavIcon;

  if (key.includes('overview') || key.includes('dashboard')) {
    IconComponent = OverviewIcon;
  } else if (
    key.includes('new') ||
    key.includes('create') ||
    key.includes('plus')
  ) {
    IconComponent = NewRequestIcon;
  } else if (
    key.includes('my requests') ||
    key.includes('request') ||
    key.includes('package') ||
    key.includes('order')
  ) {
    IconComponent = RequestsIcon;
  } else if (
    key.includes('track') ||
    key.includes('location') ||
    key.includes('map')
  ) {
    IconComponent = TrackIcon;
  } else if (
    key.includes('chat') ||
    key.includes('support') ||
    key.includes('message')
  ) {
    IconComponent = ChatIcon;
  } else if (
    key.includes('rider') ||
    key.includes('truck') ||
    key.includes('delivery')
  ) {
    IconComponent = RiderIcon;
  } else if (
    key.includes('admin') ||
    key.includes('shield') ||
    key.includes('manage')
  ) {
    IconComponent = AdminIcon;
  }

  return <IconComponent className={iconClassName} />;
};
